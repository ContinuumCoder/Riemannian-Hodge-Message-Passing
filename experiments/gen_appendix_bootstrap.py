"""
Generate appendix LaTeX tables from bootstrap_metrics.json.

Produces a single file with per-task tables showing mean±std for all metrics.
"""
import json, os

ROOT = os.path.join(os.path.dirname(__file__), '..')
BOOT = json.load(open(os.path.join(ROOT, 'checkpoints/bootstrap_metrics.json')))

# Display names
TASK_NAME = {
    'T1': r'NS Vort$^\dagger$',
    'T2': 'Torus Adv',
    'T3_T3_ellipsoid_surface_flow': 'Ellips Flow',
    'T5': 'Maxwell',
    'T6': 'Wilson',
    'T7': 'Yang--Mills',
    'T8': r'Airfoil$^\dagger$',
}
TASK_ORDER = ['T1', 'T2', 'T3_T3_ellipsoid_surface_flow', 'T5', 'T6', 'T7', 'T8']

MODEL_NAME = {
    'gcn': 'GCN', 'gat': 'GAT', 'schnet': 'SchNet', 'egnn': 'EGNN',
    'mpsn': 'MPSN', 'sccnn': 'SCCNN',
    'gauge_cnn': 'GaugeEqCNN', 'gem_cnn': 'GEM-CNN',
    'cw_net': 'CW Net', 'clifford_smpn': 'Clifford-SMPN',
    'fno': 'FNO', 'deeponet': 'DeepONet', 'ours': 'Ours',
}
MODEL_ORDER = ['gcn', 'gat', 'schnet', 'egnn', 'mpsn', 'sccnn',
               'gauge_cnn', 'gem_cnn', 'cw_net', 'clifford_smpn',
               'fno', 'deeponet', 'ours']

METRICS = [('SSIM', r'$\uparrow$'), ('Pearson', r'$\uparrow$'), ('NRMSE', r'$\downarrow$')]


def fmt_cell(ms, metric):
    """Format std-only (point estimates already in the main-text table)."""
    digits = 4 if metric == 'NRMSE' else 3
    s = ms['std']
    return f"$\\pm\\,{s:.{digits}f}$"


def build_task_table(task_id):
    data = BOOT[task_id]
    lines = []
    lines.append(r'\begin{table}[t]')
    lines.append(r'\centering\small')
    lines.append(rf'\caption{{\textbf{{{TASK_NAME[task_id]}}}: bootstrap std (point estimates in main-text Table~\ref{tab:main}) over test set (1000 resamples, fixed seed=42 training).}}')
    lines.append(rf'\label{{tab:boot-{task_id.lower()}}}')
    lines.append(r'\begin{tabular}{l' + 'c' * len(METRICS) + '}')
    lines.append(r'\toprule')
    hdr = 'Model & ' + ' & '.join(f'{m} {a}' for m, a in METRICS) + r' \\'
    lines.append(hdr)
    lines.append(r'\midrule')
    for mkey in MODEL_ORDER:
        if mkey not in data: continue
        row = [MODEL_NAME[mkey]]
        for met, _ in METRICS:
            if met in data[mkey]:
                row.append(fmt_cell(data[mkey][met], met))
            else:
                row.append('---')
        lines.append(' & '.join(row) + r' \\')
    lines.append(r'\bottomrule')
    lines.append(r'\end{tabular}')
    lines.append(r'\end{table}')
    return '\n'.join(lines)


def build_compact_all(metric):
    """One big table: methods (rows) x tasks (cols), single metric, mean±std."""
    lines = [r'\begin{table}[t]', r'\centering\scriptsize',
             rf'\caption{{\textbf{{{metric}}} bootstrap std (1000 resamples over test set; '
             r'point estimates in main-text Table~\ref{tab:main}). '
             r'Each row a method, each column a task.}',
             rf'\label{{tab:boot-all-{metric.lower()}}}',
             r'\resizebox{\linewidth}{!}{%',
             r'\begin{tabular}{l' + 'c' * len(TASK_ORDER) + '}',
             r'\toprule',
             'Method & ' + ' & '.join(TASK_NAME[t].replace('&', r'\&') for t in TASK_ORDER) + r' \\',
             r'\midrule']
    for m in MODEL_ORDER:
        row = [MODEL_NAME[m]]
        for t in TASK_ORDER:
            data = BOOT.get(t, {})
            if m in data and metric in data[m]:
                row.append(fmt_cell(data[m][metric], metric))
            else:
                row.append('N/A')
        lines.append(' & '.join(row) + r' \\')
    lines.extend([r'\bottomrule', r'\end{tabular}%', r'}', r'\end{table}'])
    return '\n'.join(lines)


def main():
    out_dir = '/home/dzheng/GaugeStructuredHodgeMP_report/paper/Formatting_Instructions_For_NeurIPS_2026EN'
    out_path = os.path.join(out_dir, 'appendix_bootstrap.tex')

    chunks = []
    # Header / methodology blurb
    chunks.append(r'''% Auto-generated by experiments/gen_appendix_bootstrap.py
% Bootstrap-over-test-set statistics. 1000 resamples with replacement of
% the full test set (100 samples for gridded tasks; 50 per-sample meshes
% for the Airfoil task). All checkpoints are the best-epoch weights from
% seed=42 training.

\subsection{Test-set bootstrap statistics}
\label{app:bootstrap}

Because re-training every (task, method) combination across many random
seeds is computationally prohibitive (single-seed total: $\approx 17$ GPU-hours
for our suite), we quantify evaluation uncertainty via standard
non-parametric bootstrap resampling of the held-out test set. For each
(task, method) we load the best-epoch checkpoint (trained once with
seed $=42$), run inference on the entire test set, and then draw $B=1000$
bootstrap samples of the test indices with replacement, recomputing every
metric on each resample. We report the standard deviation across the $B$ resamples;
point estimates are given in the main-text Table~\ref{tab:main}
and not duplicated here. The NRMSE uses the fixed global data range (a property
of the dataset, not the resample); SSIM and Pearson are averaged over
per-sample values selected by the resample indices; R${}^2$, MSE and MAE
are recomputed from scratch on each bootstrap set. This quantifies
uncertainty due to finite test size but does not capture seed-to-seed
training variance; we acknowledge this limitation.

Tables \ref{tab:boot-all-ssim}--\ref{tab:boot-all-nrmse} below report
bootstrap statistics for all three metrics used in the main paper.
''')

    # Compact: one table per metric (rows=tasks, cols=models)
    for metric, _ in METRICS:
        chunks.append(build_compact_all(metric))
        chunks.append('')

    with open(out_path, 'w') as f:
        f.write('\n\n'.join(chunks))
    print(f'Wrote: {out_path}')


if __name__ == '__main__':
    main()
